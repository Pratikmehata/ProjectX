// ─── Helpers ─────────────────────────────────────────────────────────────────

function formatINR(n) {
  return new Intl.NumberFormat("en-IN", {
    maximumFractionDigits: 0,
    minimumFractionDigits: 0,
  }).format(n);
}

function getBuildText(result) {
  const c     = result?.build?.components || {};
  const lines = ["🚀 RIGCRAFT BUILD RECOMMENDATION", "═".repeat(50), ""];
  if (result.intent) lines.push(`🎯 Use Case    : ${result.intent}`);
  if (result.tier)   lines.push(`📊 Tier        : ${result.tier}`);
  lines.push("");

  ["cpu", "gpu", "motherboard", "ram", "storage"].forEach((k) => {
    if (c[k]) {
      const price = c[k].Price || c[k].price || 0;
      lines.push(`${COMP_ICONS[k]} ${k.toUpperCase().padEnd(12)}: ${c[k].Name || c[k].name}`);
      lines.push(`   ${" ".padEnd(12)}  ₹${formatINR(price)}`);
      lines.push("");
    }
  });

  if (result.psu_wattage)  lines.push(`⚡ PSU         : ${result.psu_wattage}`);
  if (result.cabinet_type) lines.push(`🗄️ Cabinet     : ${result.cabinet_type}`);
  lines.push("");
  if (result.build?.total_price) {
    lines.push(`💰 TOTAL       : ₹${formatINR(result.build.total_price)}`);
    lines.push(`   (All prices include estimated taxes)`);
  }
  lines.push("", "─".repeat(50), "Generated by Rigcraft · rigcraft.app");
  return lines.join("\n");
}


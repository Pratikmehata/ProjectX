// ─── DonutChart ───────────────────────────────────────────────────────────────

function DonutChart({ components }) {
  const order = ["cpu", "gpu", "motherboard", "ram", "storage"];
  const items = order
    .filter((k) => components[k])
    .map((k) => ({
      key: k,
      price: Number(components[k].Price || components[k].price || 0),
      color: COMP_COLORS[k],
      icon: COMP_ICONS[k],
      name: components[k].Name || components[k].name || k,
    }))
    .filter((i) => i.price > 0);

  const total = items.reduce((s, i) => s + i.price, 0);
  if (!total) return null;

  const cx = 90, cy = 90, r = 70, strokeW = 20;
  const circumference = 2 * Math.PI * r;
  let cumulativeOffset = 0;

  const segments = items.map((item) => {
    const pct  = item.price / total;
    const dash = pct * circumference;
    const seg  = { ...item, pct, dash, gap: circumference - dash, offset: cumulativeOffset };
    cumulativeOffset += dash;
    return seg;
  });

  const [hovered, setHovered] = useState(null);
  const active = hovered !== null ? items[hovered] : null;

  return (
    <div style={{ background: "rgba(0,0,0,0.2)", borderRadius: 20, padding: 20, marginTop: 20 }}>
      <div style={{ fontSize: 12, letterSpacing: 2, color: "#888", fontFamily: "'Space Mono', monospace", marginBottom: 16 }}>
        BUDGET BREAKDOWN
      </div>
      <div style={{ display: "flex", alignItems: "center", gap: 24, flexWrap: "wrap" }}>
        {/* SVG donut */}
        <div style={{ position: "relative", flexShrink: 0 }}>
          <svg width={180} height={180}>
            {segments.map((seg, i) => (
              <circle
                key={seg.key}
                cx={cx} cy={cy} r={r}
                fill="none"
                stroke={seg.color}
                strokeWidth={hovered === i ? strokeW + 4 : strokeW}
                strokeDasharray={`${seg.dash} ${seg.gap}`}
                strokeDashoffset={-seg.offset + circumference / 4}
                style={{ cursor: "pointer", transition: "stroke-width 0.2s" }}
                onMouseEnter={() => setHovered(i)}
                onMouseLeave={() => setHovered(null)}
              />
            ))}
          </svg>
          <div style={{
            position: "absolute", top: "50%", left: "50%",
            transform: "translate(-50%,-50%)", textAlign: "center",
          }}>
            {active ? (
              <>
                <div style={{ fontSize: 11, color: active.color, fontFamily: "'Space Mono', monospace" }}>
                  {active.icon}
                </div>
                <div style={{ fontSize: 13, fontWeight: 700, color: "#fff", fontFamily: "'Space Mono', monospace" }}>
                  {(active.pct * 100).toFixed(0)}%
                </div>
              </>
            ) : (
              <>
                <div style={{ fontSize: 10, color: "#555", fontFamily: "'Space Mono', monospace", letterSpacing: 1 }}>
                  TOTAL
                </div>
                <div style={{ fontSize: 14, fontWeight: 700, color: "#f0c040", fontFamily: "'Space Mono', monospace" }}>
                  ₹{formatINR(total)}
                </div>
              </>
            )}
          </div>
        </div>

        {/* Legend */}
        <div style={{ flex: 1, minWidth: 120 }}>
          {items.map((item, i) => (
            <div
              key={item.key}
              onMouseEnter={() => setHovered(i)}
              onMouseLeave={() => setHovered(null)}
              style={{
                display: "flex", alignItems: "center", gap: 8,
                marginBottom: 8, cursor: "pointer",
                opacity: hovered !== null && hovered !== i ? 0.4 : 1,
                transition: "opacity 0.2s",
              }}
            >
              <div style={{ width: 8, height: 8, borderRadius: "50%", background: item.color, flexShrink: 0 }} />
              <div style={{ flex: 1, fontSize: 12, color: "#aaa", fontFamily: "'DM Sans', sans-serif" }}>
                {item.key.toUpperCase()}
              </div>
              <div style={{ fontSize: 12, color: "#fff", fontFamily: "'Space Mono', monospace" }}>
                ₹{formatINR(item.price)}
              </div>
            </div>
          ))}
        </div>
      </div>
    </div>
  );
}

